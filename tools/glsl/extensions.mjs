// glslang が知っている拡張の名前の一覧を、glslang の実行ファイルから作る。
//
// 使い方 (リポジトリのルートで):
//   GLSLANG=<glslang の実行ファイル> node tools/glsl/extensions.mjs
//
// GLSLANG を渡さなければ、PATH の glslang を使用する。glslang はリポジトリに入れない
// (https://github.com/KhronosGroup/glslang/releases から取る)。
// 実行ファイルに含まれる「GL_」で始まる文字列を候補にし、1 つずつ「#extension <名前> : require」を書いたシェーダーを glslang に渡す。
// glslang が「extension not supported」を出さなかったものが、glslang の知っている拡張である
// (glslang の Versions.cpp の initializeExtensionBehavior が登録するもの。プロファイルやバージョンで変わらない)。
// src/Shaderlyn.Rules/Glsl/GlslKnownExtensions.g.cs を書き出す。解析の実行時には glslang を使用しない。

import { execFileSync, spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const output = join(root, 'src', 'Shaderlyn.Rules', 'Glsl', 'GlslKnownExtensions.g.cs');
const glslang = process.env.GLSLANG || 'glslang';

// -dumpfullversion は「11:16.6.0」の形で出る。コロンの後ろがリリースのバージョンである。
const version = execFileSync(glslang, ['-dumpfullversion'], { encoding: 'utf8' }).trim().split(':').pop();

// PATH から探す場合は、実行ファイルの場所が分からないので、where / which で探す。
function executablePath() {
  if (process.env.GLSLANG) {
    return process.env.GLSLANG;
  }

  const finder = process.platform === 'win32' ? 'where' : 'which';
  return execFileSync(finder, [glslang], { encoding: 'utf8' }).split(/\r?\n/)[0].trim();
}

const binary = readFileSync(executablePath()).toString('latin1');
const candidates = [...new Set(binary.match(/GL_[A-Za-z0-9_]+/g) ?? [])].sort();

const work = mkdtempSync(join(tmpdir(), 'shaderlyn-glsl-ext-'));
const known = [];
try {
  const file = join(work, 'probe.frag');
  for (const name of candidates) {
    writeFileSync(file, `#version 450\n#extension ${name} : require\nvoid main() { }\n`);
    const run = spawnSync(glslang, [file], { encoding: 'utf8' });
    const text = `${run.stdout ?? ''}${run.stderr ?? ''}`;
    if (!text.includes('extension not supported')) {
      known.push(name);
    }
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}

const lines = known.map(name => `        "${name}",`).join('\n');
writeFileSync(output, `// <auto-generated>
// tools/glsl/extensions.mjs が glslang ${version} から作った。手で書き換えない。
// </auto-generated>

using System.Collections.Frozen;

namespace Shaderlyn.Rules.Glsl;

/// <summary>glslang ${version} が知っている拡張の名前。</summary>
/// <remarks>
/// 一覧にない拡張を <c>#extension … : require</c> と書くと、glslang はコンパイルの誤り (extension not supported) にする。
/// </remarks>
internal static class GlslKnownExtensions
{
    /// <summary>拡張の名前の集合。</summary>
    public static FrozenSet<string> Names { get; } = new[]
    {
${lines}
    }.ToFrozenSet(StringComparer.Ordinal);
}
`.replace(/\n/g, '\r\n'));

console.log(`${known.length} 個の拡張を ${output} に書き出しました (候補 ${candidates.length} 個)。`);
