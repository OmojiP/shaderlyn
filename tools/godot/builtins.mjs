// Godot シェーダー言語の組み込みの変数と描画のモードの表を、Godot のソース (servers/rendering/shader_types.cpp) から作る。
//
// 使い方 (リポジトリのルートで):
//   node tools/godot/builtins.mjs [<Godot のソースのフォルダー>]   (既定は .work/corpus/godot。tools/corpus/fetch.mjs --only=godot で取る)
//
// src/Shaderlyn.Semantics/Symbols/GodotBuiltins.g.txt を書き出す。解析の実行時には Godot のソースを使わない。
// 同じソースで作り直せば、表は 1 文字も変わらない (並びは元のファイルの順のまま)。
// 表は Godot の shader_types.cpp に書かれた宣言を元にするので、生成したファイルの先頭に Godot の名前と版を入れる
// (ライセンスは THIRD-PARTY-NOTICES.txt)。

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const source = resolve(process.argv[2] ?? join(root, '.work', 'corpus', 'godot'));
const output = join(root, 'src', 'Shaderlyn.Semantics', 'Symbols', 'GodotBuiltins.g.txt');

const text = readFileSync(join(source, 'servers', 'rendering', 'shader_types.cpp'), 'utf8');
const version = readVersion(join(source, 'version.py'));

/** RSE::SHADER_CANVAS_ITEM → canvas_item (shader_type に書く名前)。 */
const shaderType = name => name.toLowerCase();

const lines = [
  '# <auto-generated>',
  '# tools/godot/builtins.mjs が生成した。手で書き換えないこと。',
  `# 元のデータ: Godot ${version} の servers/rendering/shader_types.cpp (https://github.com/godotengine/godot)。ライセンスは THIRD-PARTY-NOTICES.txt にある。`,
  '#',
  '# V shader_type 関数 (global はどの関数でも、constants は関数の外でも使える) 名前 型 (const は書き込めない)',
  '# F shader_type 関数 (ステージ関数) discard を使えるか (discard / -)',
  '# R shader_type 描画のモード (render_mode に書く名前)',
  '# S shader_type ステンシルのモード (stencil_mode に書く名前。参照値の数は別に書く)',
  '# </auto-generated>',
];

// shader_modes[RSE::SHADER_SPATIAL].functions["vertex"].built_ins["VERTEX"] = ShaderLanguage::TYPE_VEC3;
// shader_modes[RSE::SHADER_SPATIAL].functions["global"].built_ins["TIME"] = constt(ShaderLanguage::TYPE_FLOAT);
const builtin = /shader_modes\[RSE::SHADER_(\w+)\]\.functions\["(\w+)"\]\.built_ins\["(\w+)"\] = (const[a-z]*\()?ShaderLanguage::TYPE_(\w+)/g;
for (const m of text.matchAll(builtin)) {
  lines.push(['V', shaderType(m[1]), m[2], m[3], m[5].toLowerCase().replace('sampler2d', 'sampler2D').replace('samplercube', 'samplerCube'), m[4] ? 'const' : 'var'].join('\t'));
}

// shader_modes[RSE::SHADER_SPATIAL].functions["fragment"].can_discard = true;
const discard = /shader_modes\[RSE::SHADER_(\w+)\]\.functions\["(\w+)"\]\.can_discard = (true|false);/g;
for (const m of text.matchAll(discard)) {
  lines.push(['F', shaderType(m[1]), m[2], m[3] === 'true' ? 'discard' : '-'].join('\t'));
}

// shader_modes[RSE::SHADER_SPATIAL].modes.push_back({ PNAME("blend"), "mix", "add" });       → blend_mix, blend_add
// shader_modes[RSE::SHADER_SPATIAL].modes.push_back({ PNAME("depth_test"), { "default", "disabled" } });
// shader_modes[RSE::SHADER_SPATIAL].modes.push_back({ PNAME("unshaded") });                 → unshaded
// ステンシルのモード (stencil_modes) も同じ形である。
const mode = /shader_modes\[RSE::SHADER_(\w+)\]\.(modes|stencil_modes)\.push_back\(\{ PNAME\("(\w+)"\)(.*)\}\);/g;
for (const m of text.matchAll(mode)) {
  const options = [...m[4].matchAll(/"(\w+)"/g)].map(o => o[1]);
  for (const name of options.length === 0 ? [m[3]] : options.map(o => `${m[3]}_${o}`)) {
    lines.push([m[2] === 'modes' ? 'R' : 'S', shaderType(m[1]), name].join('\t'));
  }
}

writeFileSync(output, lines.join('\n') + '\n');
console.log(`${output} を書きました (${lines.length} 行)`);

/** version.py の major / minor / patch から版を作る。 */
function readVersion(path) {
  const py = readFileSync(path, 'utf8');
  const get = key => py.match(new RegExp(`^${key} = (\\d+)`, 'm'))?.[1];
  return [get('major'), get('minor'), get('patch')].filter(Boolean).join('.');
}
