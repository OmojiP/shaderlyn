// Godot シェーダー言語の組み込みの変数・描画のモード・組み込み関数の表を、Godot のソース
// (servers/rendering/shader_types.cpp と shader_language.cpp) から作る。
//
// 使い方 (リポジトリのルートで):
//   node tools/godot/builtins.mjs [<Godot のソースのフォルダー>]   (既定は .work/corpus/godot。tools/corpus/fetch.mjs --only=godot で取る)
//
// src/Shaderlyn.Semantics/Symbols/GodotBuiltins.g.txt を書き出す。解析の実行時には Godot のソースを使わない。
// 同じソースで作り直せば、表は 1 文字も変わらない (並びは元のファイルの順のまま)。
// 表は Godot の shader_types.cpp に書かれた宣言を元にするので、生成したファイルの先頭に Godot の名前と版を入れる
// (ライセンスは THIRD-PARTY-NOTICES.txt)。

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const source = resolve(process.argv[2] ?? join(root, '.work', 'corpus', 'godot'));
const output = join(root, 'src', 'Shaderlyn.Semantics', 'Symbols', 'GodotBuiltins.g.txt');

const text = readFileSync(join(source, 'servers', 'rendering', 'shader_types.cpp'), 'utf8');
const version = readVersion(join(source, 'version.py'));

/** RSE::SHADER_CANVAS_ITEM → canvas_item (shader_type に書く名前)。 */
const shaderType = name => name.toLowerCase();

const lines = [
  '# <auto-generated>',
  '# tools/godot/builtins.mjs が生成した。手で書き換えないこと。',
  `# 元のデータ: Godot ${version} の servers/rendering/shader_types.cpp と shader_language.cpp (https://github.com/godotengine/godot)。ライセンスは THIRD-PARTY-NOTICES.txt にある。`,
  '#',
  '# V shader_type 関数 (global はどの関数でも、constants は関数の外でも使える) 名前 型 (const は書き込めない)',
  '# F shader_type 関数 (ステージ関数) discard を使えるか (discard / -)',
  '# R shader_type 描画のモード (render_mode に書く名前)',
  '# S shader_type ステンシルのモード (stencil_mode に書く名前。参照値の数は別に書く)',
  '# P shader_type 関数 (ステージ関数) 組み込み関数の名前 戻り値の型 仮引数の型 (, で区切る。その関数の中でだけ使える)',
  '# B 組み込み関数の名前 戻り値の型 仮引数の型 (, で区切る) high_end (high-end の描画でだけ使える) か - (shader_language.cpp の builtin_func_defs)',
  '# O 組み込み関数の名前 out の仮引数の位置 (0 から。builtin_func_out_args)',
  '# K 組み込み関数の名前 定数でなければならない実引数の位置 最小 最大 (builtin_func_const_args)',
  '# G フラグメントと light の関数でだけ使える組み込み関数の名前 (frag_only_func_defs)',
  '# </auto-generated>',
];

/** TYPE_VEC2 → vec2 (ステージ関数の組み込み関数の型。表に出る型だけを知っていればよい)。 */
const stageType = t => t.toLowerCase().replace('sampler2d', 'sampler2D').replace('samplercube', 'samplerCube');

// shader_modes[RSE::SHADER_SPATIAL].functions["vertex"].built_ins["VERTEX"] = ShaderLanguage::TYPE_VEC3;
// shader_modes[RSE::SHADER_SPATIAL].functions["global"].built_ins["TIME"] = constt(ShaderLanguage::TYPE_FLOAT);
const builtin = /shader_modes\[RSE::SHADER_(\w+)\]\.functions\["(\w+)"\]\.built_ins\["(\w+)"\] = (const[a-z]*\()?ShaderLanguage::TYPE_(\w+)/g;
for (const m of text.matchAll(builtin)) {
  lines.push(['V', shaderType(m[1]), m[2], m[3], m[5].toLowerCase().replace('sampler2d', 'sampler2D').replace('samplercube', 'samplerCube'), m[4] ? 'const' : 'var'].join('\t'));
}

// shader_modes[RSE::SHADER_SPATIAL].functions["fragment"].can_discard = true;
const discard = /shader_modes\[RSE::SHADER_(\w+)\]\.functions\["(\w+)"\]\.can_discard = (true|false);/g;
for (const m of text.matchAll(discard)) {
  lines.push(['F', shaderType(m[1]), m[2], m[3] === 'true' ? 'discard' : '-'].join('\t'));
}

// shader_modes[RSE::SHADER_SPATIAL].modes.push_back({ PNAME("blend"), "mix", "add" });       → blend_mix, blend_add
// shader_modes[RSE::SHADER_SPATIAL].modes.push_back({ PNAME("depth_test"), { "default", "disabled" } });
// shader_modes[RSE::SHADER_SPATIAL].modes.push_back({ PNAME("unshaded") });                 → unshaded
// ステンシルのモード (stencil_modes) も同じ形である。
const mode = /shader_modes\[RSE::SHADER_(\w+)\]\.(modes|stencil_modes)\.push_back\(\{ PNAME\("(\w+)"\)(.*)\}\);/g;
for (const m of text.matchAll(mode)) {
  const options = [...m[4].matchAll(/"(\w+)"/g)].map(o => o[1]);
  for (const name of options.length === 0 ? [m[3]] : options.map(o => `${m[3]}_${o}`)) {
    lines.push([m[2] === 'modes' ? 'R' : 'S', shaderType(m[1]), name].join('\t'));
  }
}

// ステージ関数ごとの組み込み関数 (canvas_item の texture_sdf、particles の emit_subparticle など)。
// StageFunctionInfo に仮引数と戻り値の型を足してから、関数に割り当てる。行の順に読んで組み立てる。
//   ShaderLanguage::StageFunctionInfo func;
//   func.arguments.push_back(ShaderLanguage::StageFunctionInfo::Argument("sdf_pos", ShaderLanguage::TYPE_VEC2));
//   func.return_type = ShaderLanguage::TYPE_FLOAT;
//   shader_modes[RSE::SHADER_CANVAS_ITEM].functions["fragment"].stage_functions["texture_sdf"] = func;
{
  let args = [];
  let returnType = 'VOID';
  for (const line of text.split('\n')) {
    if (/StageFunctionInfo \w+;/.test(line)) {
      args = [];
      returnType = 'VOID';
    }
    const arg = /\.arguments\.push_back\(.*TYPE_(\w+)\)\);/.exec(line);
    if (arg) {
      args.push(arg[1]);
    }
    const ret = /\.return_type = ShaderLanguage::TYPE_(\w+);/.exec(line);
    if (ret) {
      returnType = ret[1];
    }
    const assign = /shader_modes\[RSE::SHADER_(\w+)\]\.functions\["(\w+)"\]\.stage_functions\["(\w+)"\] = \w+;/.exec(line);
    if (assign) {
      lines.push(['P', shaderType(assign[1]), assign[2], assign[3], stageType(returnType), args.map(stageType).join(',')].join('\t'));
    }
  }
}

// 組み込み関数は shader_language.cpp の表から読む。
const language = readFileSync(join(source, 'servers', 'rendering', 'shader_language.cpp'), 'utf8');

/** TYPE_SAMPLER2DARRAY → sampler2DArray (シェーダーに書く型の名前)。 */
const typeNames = new Map([
  'void', 'bool', 'bvec2', 'bvec3', 'bvec4', 'int', 'ivec2', 'ivec3', 'ivec4', 'uint', 'uvec2', 'uvec3', 'uvec4',
  'float', 'vec2', 'vec3', 'vec4', 'mat2', 'mat3', 'mat4',
  'sampler2D', 'isampler2D', 'usampler2D', 'sampler2DArray', 'isampler2DArray', 'usampler2DArray',
  'sampler3D', 'isampler3D', 'usampler3D', 'samplerCube', 'samplerCubeArray',
].map(name => [name.toUpperCase(), name]));
typeNames.set('SAMPLEREXT', 'samplerExternalOES');
const typeName = t => typeNames.get(t) ?? (() => { throw new Error(`知らない型 TYPE_${t}`); })();

// { "vec3", TYPE_VEC3, { TYPE_VEC2, TYPE_FLOAT, TYPE_VOID }, { "" }, TAG_GLOBAL, false },
const tableOf = name => {
  const start = language.indexOf(`${name}[] = {`);
  if (start < 0) {
    throw new Error(`${name} がありません`);
  }
  return language.slice(start, language.indexOf('\n};', start));
};
const functionDef = /\{ "(\w+)", TYPE_(\w+), \{ ([^}]*) \}, \{[^}]*\}, (\w+), (true|false) \}/g;
for (const m of tableOf('builtin_func_defs').matchAll(functionDef)) {
  const args = m[3].split(',').map(a => a.trim().replace(/^TYPE_/, '')).filter(a => a !== 'VOID').map(typeName);
  lines.push(['B', m[1], typeName(m[2]), args.join(','), m[5] === 'true' ? 'high_end' : '-'].join('\t'));
}

// { "modf", { 1, -1 } },  → 1 番目 (0 から数える) の実引数は out
for (const m of tableOf('builtin_func_out_args').matchAll(/\{ "(\w+)", \{ ([^}]*) \} \}/g)) {
  for (const index of m[2].split(',').map(a => Number(a.trim())).filter(a => a >= 0)) {
    lines.push(['O', m[1], index].join('\t'));
  }
}

// { "textureGather", 2, 0, 3 },  → 2 番目の実引数は 0 以上 3 以下の定数
for (const m of tableOf('builtin_func_const_args').matchAll(/\{ "(\w+)", (\d+), (\d+), (\d+) \}/g)) {
  lines.push(['K', m[1], m[2], m[3], m[4]].join('\t'));
}

// { "dFdx" },  → フラグメントと light の関数でだけ使える
for (const m of tableOf('frag_only_func_defs').matchAll(/\{ "(\w+)" \}/g)) {
  lines.push(['G', m[1]].join('\t'));
}

writeFileSync(output, lines.join('\n') + '\n');
console.log(`${output} を書きました (${lines.length} 行)`);

/** version.py の major / minor / patch から版を作る。 */
function readVersion(path) {
  const py = readFileSync(path, 'utf8');
  const get = key => py.match(new RegExp(`^${key} = (\\d+)`, 'm'))?.[1];
  return [get('major'), get('minor'), get('patch')].filter(Boolean).join('.');
}
